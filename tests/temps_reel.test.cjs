const assert=require('node:assert/strict');
const R=require('../cm3/temps-reel.js');
const now=Date.parse('2026-10-23T13:30:00Z');
const fresh={time:now-30000,state:'en_service',occupation:'libre'};
assert.equal(R.classify(fresh,now),'available');
assert.equal(R.classify({...fresh,state:'hors_service'},now),'out','hors service prime sur libre');
assert.equal(R.classify({...fresh,state:'inconnu'},now),'unknown');
assert.equal(R.classify({...fresh,time:now-R.MAX_AGE-1},now),'unknown','jamais disponible si périmé');
assert.equal(R.classify({...fresh,time:now+121000},now),'unknown','date future excessive');
assert.ok(Number.isNaN(R.timestamp('2026-10-23 13:29:30')),'pas de fuseau deviné');
assert.equal(R.timestamp('2026-10-23 13:29:30.123456+00:00'),Date.parse('2026-10-23T13:29:30.123Z'));
const rows=R.parseCSV('\ufeffid_pdc_itinerance,etat_pdc,occupation_pdc,horodatage,note\r\nFR1,en_service,libre,2026-10-23T13:29:30Z,"a,b\n""c"""\r\nFR1,en_service,occupe,2026-10-23T13:29:30Z,x\r\nFR2,en_service,libre,2026-10-23T13:29:30Z,x\r\nFR2,hors_service,inconnu,2026-10-23T13:29:40Z,x');
assert.equal(rows[0].note,'a,b\n"c"');
const index=R.indexRows(rows);
assert.equal(R.classify(index.get('FR1'),now),'unknown','doublon contradictoire à même date');
assert.equal(R.classify(index.get('FR2'),now),'out','version la plus récente');
const counts=R.summarize({points:10,ids:['A','B','C','D','E','F','G','H','I','J']},new Map([['A',fresh],['B',{...fresh,occupation:'occupe'}],['C',{...fresh,time:now-R.MAX_AGE-1}]]),now);
assert.equal(counts.available,1);assert.equal(counts.busy,1);assert.equal(counts.unknown,8);
assert.equal(counts.available+counts.busy+counts.out+counts.reserved+counts.unknown,10);
assert.equal(R.summarize({points:2,ids:['A','A']},new Map([['A',fresh]]),now).unknown,2,'pas de double comptage');
assert.throws(()=>R.parseCSV('bad,header\na,b'));
console.log('Tests temps réel : fraîcheur, priorités, dates, doublons, CSV et couverture partielle OK.');
